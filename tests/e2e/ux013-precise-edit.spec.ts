import { test, expect } from "@playwright/test";
import { prepareCoreSourceResume, readStore } from "./support/p51CoreWorkflow";
import { mkdir, writeFile } from "node:fs/promises";
import type { ResumeBranch } from "@/domain/schemas";

test("UX013 explicit field selection review refresh and one authoritative Revision", async ({ page }, info) => {
  test.setTimeout(120_000);
  // No model quota or runtime request: this exercises the user-entered wording route through the same Facade/Gateway.
  await page.route("**/api/ai/**", route => route.abort());
  await page.goto("/setup");
  await page.getByRole("button", { name: "跳过，先体验其他功能" }).click();
  await prepareCoreSourceResume(page);
  const before = { branches: await readStore(page, "resumeBranches"), profiles: await readStore(page, "profiles"), revisions: await readStore(page, "resumeRevisions") };
  await mkdir("docs/quality/ux-01.3-a0-a1-logs", { recursive: true });
  await writeFile("docs/quality/ux-01.3-a0-a1-logs/browser-before.json", JSON.stringify(before, null, 2));
  const branch = before.branches.find(b => b.branchPurpose === "general") as unknown as ResumeBranch;
  expect(branch).toBeTruthy();
  await page.goto("/ai-workspace");
  await page.getByRole("button", { name: "新任务", exact: true }).click();
  const panel = page.getByTestId("precise-resume-editor");
  await panel.locator("summary").click();
  await panel.getByLabel("精确修改简历", { exact: true }).selectOption(branch.id);
  const option = await panel.getByLabel("精确修改字段", { exact: true }).locator("option").filter({ hasText: /要点 1/ }).getAttribute("value");
  expect(option).toBeTruthy();
  await panel.getByLabel("精确修改字段", { exact: true }).selectOption(option!);
  await panel.getByRole("button", { name: "选择此字段", exact: true }).click();
  await panel.getByLabel("建议措辞", { exact: true }).fill("参加 AI 应用项目的需求梳理、原型设计和功能验收。");
  await panel.getByRole("button", { name: "生成审核提案", exact: true }).click();
  await expect(panel.getByRole("region", { name: "精确修改审核" })).toBeVisible();
  expect(await readStore(page, "resumeRevisions")).toEqual(before.revisions);
  await page.reload();
  await panel.locator("summary").click();
  await expect(panel.getByText("建议：参加 AI 应用项目的需求梳理、原型设计和功能验收。", { exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath("proposal.png"), fullPage: true });
  await panel.getByRole("button", { name: "确认修改", exact: true }).click();
  await expect(panel.getByText(/已保存版本：/)).toBeVisible();
  const after = { branches: await readStore(page, "resumeBranches"), profiles: await readStore(page, "profiles"), revisions: await readStore(page, "resumeRevisions") };
  expect(after.profiles).toEqual(before.profiles);
  expect(after.branches).toHaveLength(before.branches.length);
  expect(after.revisions).toHaveLength(before.revisions.length + 1);
  const revised = after.branches.find(b => b.id === branch.id) as unknown as ResumeBranch;
  const revisionId = revised.currentRevisionId;
  expect(after.revisions.some(r => r.id === revisionId && r.previousRevisionId === branch.currentRevisionId)).toBe(true);
  await page.reload(); await panel.locator("summary").click();
  await expect(panel.getByText(`已保存版本：${revisionId}`, { exact: true })).toBeVisible();
  expect(await readStore(page, "resumeRevisions")).toEqual(after.revisions);
  await page.screenshot({ path: info.outputPath("saved.png"), fullPage: true });
  await mkdir("docs/quality/ux-01.3-a0-a1-logs", { recursive: true });
  await writeFile("docs/quality/ux-01.3-a0-a1-logs/browser-data.json", JSON.stringify({ before, after, revisionId }, null, 2));
});
