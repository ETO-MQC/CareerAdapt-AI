import { expect, test } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { referenceCampusResume } from "../fixtures/resume-v2/referenceCampus";

test("default reference template preserves education and skill fields in preview and PDF", async ({ page }) => {
  test.setTimeout(120_000);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/setup");
  await page.getByRole("button", { name: "跳过，先体验其他功能" }).click();
  await page.goto("/resume");
  await page.getByRole("button", { name: "导入已有简历 核对来源后创建通用简历" }).click();
  await page.getByLabel("选择要导入的简历文件").setInputFiles({ name: "reference-fields.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(referenceCampusResume())) });
  await page.getByLabel("创建新人物").check();
  await page.locator('input[name="new-profile-name"]').fill("林同学");
  const structure = page.getByRole("button", { name: "确认全部当前结构", exact: true });
  if (await structure.isVisible()) await structure.click();
  const sources = page.getByRole("button", { name: "核对并保留来源", exact: true });
  while (await sources.count()) await sources.first().click();
  await expect(page.getByRole("button", { name: "确认导入", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "确认导入", exact: true }).click();
  await expect(page.getByTestId("resume-studio-shell")).toBeVisible();
  const pages = page.locator('.resume-page-shell [data-testid="resume-a4-page"]');
  await expect(pages.first()).toHaveClass(/template-classic-technical/);
  const education = page.locator('.resume-page-shell [data-render-section="education"]').first();
  await expect(education).toContainText("3.6");
  await expect(education).toContainText("前 15%");
  await expect(education).toContainText("核心课程");
  const labels = await education.locator('[data-pagination-unit^="custom-rows:education-"]').evaluateAll(rows => rows.map(row => row.textContent));
  expect(labels[0]).toContain("GPA");
  expect(labels[0]).toContain("专业排名");
  expect(labels[1]).toContain("核心课程");
  for (const value of ["Excel", "Python", "SQL", "CET6", "数据库应用认证"]) await expect(page.locator('.resume-preview-pages')).toContainText(value);
  await expect(async () => { await pages.first().screenshot({ path: ".tmp/reference-fields-preview.png" }); }).toPass({ timeout: 20000 });
  const coverage = await page.evaluate(() => {
    const measurement = document.querySelector('[data-testid="resume-pagination-measurement-page"]')!;
    const ids = (root: Element) => [...root.querySelectorAll<HTMLElement>('[data-coverage-item-id][data-render-fragment-index="0"]')].map(el => el.dataset.coverageItemId).sort();
    const renderedPages = [...document.querySelectorAll<HTMLElement>('.resume-page-shell [data-testid="resume-a4-page"]')];
    const clipped = renderedPages.flatMap(p => { const boundary = p.getBoundingClientRect(); return [...p.querySelectorAll<HTMLElement>('[data-pagination-unit]')].filter(el => { const box = el.getBoundingClientRect(); return box.bottom > boundary.bottom + 2 || box.right > boundary.right + 2; }).map(el => el.textContent); });
    return { source: ids(measurement), rendered: renderedPages.flatMap(ids).sort(), clipped };
  });
  expect(coverage.rendered).toEqual(coverage.source);
  expect(coverage.clipped).toEqual([]);
  const download = page.waitForEvent("download", { timeout: 30000 });
  await page.getByTestId("resume-studio-workbar").getByRole("button", { name: "下载 PDF" }).click();
  const file = await download;
  const pdfPath = resolve('.tmp/reference-fields.pdf');
  await file.saveAs(pdfPath);
  const text = execFileSync('pdftotext', ['-enc', 'UTF-8', pdfPath, '-'], { encoding: 'utf8' }).replace(/\s+/gu, '');
  for (const value of ["示例大学", "3.6", "前15%", "统计学", "Excel", "Python", "SQL", "CET6", "数据库应用认证"]) expect(text).toContain(value);
});
